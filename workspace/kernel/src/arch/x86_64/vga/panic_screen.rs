//! Panic-safe framebuffer drawing.
//!
//! Provides a set of globals and direct-draw functions that allow the panic
//! handler to render a visual panic screen even when `VGA_WRITER` is locked
//! by the faulting context. The framebuffer parameters are snapshotted once
//! during `vga::init()` via `init_panic_fb_globals()` and are read-only
//! afterwards, making them safe to access from the panic path without any
//! locking.

use core::sync::atomic::{AtomicU64, Ordering};

// These globals are set once during vga::init and are read-only afterwards,
// so the panic handler can draw a panic screen even when VGA_WRITER is
// locked by the faulting context.
// =============================================================================

/// Raw framebuffer virtual address (HHDM-mapped), 0 if framebuffer is not available.
pub(crate) static PANIC_FB_ADDR: AtomicU64 = AtomicU64::new(0);
/// Framebuffer width in pixels.
pub(crate) static PANIC_FB_WIDTH: AtomicU64 = AtomicU64::new(0);
/// Framebuffer height in pixels.
pub(crate) static PANIC_FB_HEIGHT: AtomicU64 = AtomicU64::new(0);
/// Framebuffer pitch in bytes.
pub(crate) static PANIC_FB_PITCH: AtomicU64 = AtomicU64::new(0);
/// Packed pixel-format info: (bpp << 32) | (red_shift << 24) |
/// (green_shift << 16) | (blue_shift << 8) | format_flags
pub(crate) static PANIC_FB_FORMAT: AtomicU64 = AtomicU64::new(0);

/// Initialise the panic-screen framebuffer globals.
/// Must be called once from vga::init() after configure() succeeds.
pub fn init_panic_fb_globals(
    addr: u64,
    w: usize,
    h: usize,
    pitch: usize,
    bpp: u16,
    red_shift: u8,
    green_shift: u8,
    blue_shift: u8,
) {
    PANIC_FB_ADDR.store(addr, Ordering::Release);
    PANIC_FB_WIDTH.store(w as u64, Ordering::Relaxed);
    PANIC_FB_HEIGHT.store(h as u64, Ordering::Relaxed);
    PANIC_FB_PITCH.store(pitch as u64, Ordering::Relaxed);
    let fmt: u64 = (bpp as u64) << 32
        | (red_shift as u64) << 24
        | (green_shift as u64) << 16
        | (blue_shift as u64) << 8;
    PANIC_FB_FORMAT.store(fmt, Ordering::Relaxed);
}

