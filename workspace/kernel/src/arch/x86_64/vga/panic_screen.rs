/// Draw a single character at (x, y) using the panic font.
/// `fg` and `bg` are packed pixel-colour values for the current pixel format.
fn panic_draw_char(
    fb: *mut u8,
    pitch: usize,
    x: usize,
    y: usize,
    ch: u8,
    fg: u32,
    bg: u32,
    fmt: u64,
) {
    let bpp = (fmt >> 32) as u16;
    let bytes_per_pixel = (bpp / 8) as usize;
    if bytes_per_pixel == 0 {
        return;
    }
    let idx = if ch < 0x20 || ch > 0x7E {
        0usize
    } else {
        (ch - 0x20) as usize
    };
    let glyph_start = idx * 16;
    for row in 0..16 {
        let mask = PANIC_FONT_8X16[glyph_start + row];
        if mask == 0 && bg == 0 {
            continue; // skip all-bg rows for speed
        }
        let row_y = y + row;
        for col in 0..8 {
            let px = x + col;
            let pixel = if (mask >> (7 - col)) & 1 != 0 { fg } else { bg };
            // SAFETY: caller ensures (x,y) + (8,16) is within framebuffer bounds.
            unsafe {
                let offset = row_y * pitch + px * bytes_per_pixel;
                let ptr = fb.add(offset) as *mut u32;
                if bytes_per_pixel == 4 {
                    core::ptr::write_volatile(ptr, pixel);
                } else if bytes_per_pixel == 3 {
                    // 24bpp : write three bytes
                    core::ptr::write_volatile(ptr as *mut u8, pixel as u8);
                    core::ptr::write_volatile(ptr.add(1) as *mut u8, (pixel >> 8) as u8);
                    core::ptr::write_volatile(ptr.add(2) as *mut u8, (pixel >> 16) as u8);
                }
            }
        }
    }
}

/// Pack RGB into a u32 using the pixel-format globals.
pub(crate) fn panic_pack_rgb(fmt: u64, r: u8, g: u8, b: u8) -> u32 {
    let red_shift = ((fmt >> 24) & 0xFF) as u8;
    let green_shift = ((fmt >> 16) & 0xFF) as u8;
    let blue_shift = ((fmt >> 8) & 0xFF) as u8;
    (r as u32) << red_shift | (g as u32) << green_shift | (b as u32) << blue_shift
}

/// Draw a NUL-terminated ASCII string at (x, y) using the panic framebuffer.
/// Returns the X position after the last character.
fn panic_draw_str(
    fb: *mut u8,
    pitch: usize,
    mut x: usize,
    y: usize,
    s: &str,
    fg: u32,
    bg: u32,
    fmt: u64,
    max_x: usize,
) -> usize {
    for &byte in s.as_bytes() {
        if byte == 0 {
            break;
        }
        if x + 8 > max_x {
            break;
        }
        if byte == b'\n' {
            break;
        }
        panic_draw_char(fb, pitch, x, y, byte, fg, bg, fmt);
        x += 8;
    }
    x
}

/// Maximum number of lines for the panic screen.
const PANIC_SCREEN_MAX_LINES: usize = 40;

/// Draw the full panic screen directly to the framebuffer (no locking).
///
/// This is the fallback path used when `VGA_WRITER` is locked by the
/// faulting context.  It writes pixels directly to the framebuffer
/// using the global param snapshots set by `init_panic_fb_globals()`.
pub fn panic_draw_direct(lines: &[&str]) {
    let fb_addr = PANIC_FB_ADDR.load(Ordering::Acquire);
    if fb_addr == 0 {
        return;
    }
    let w = PANIC_FB_WIDTH.load(Ordering::Relaxed) as usize;
    let h = PANIC_FB_HEIGHT.load(Ordering::Relaxed) as usize;
    let pitch = PANIC_FB_PITCH.load(Ordering::Relaxed) as usize;
    let fmt = PANIC_FB_FORMAT.load(Ordering::Relaxed);
    if w == 0 || h == 0 || pitch == 0 {
        return;
    }

    let fb = fb_addr as *mut u8;
    let bg_bg = panic_pack_rgb(fmt, 0x12, 0x16, 0x1E); // dark
    let fg_txt = panic_pack_rgb(fmt, 0xFF, 0xE7, 0xA0); // amber
    let fg_err = panic_pack_rgb(fmt, 0xFF, 0x55, 0x55); // red
    let fg_title = panic_pack_rgb(fmt, 0x4F, 0xB3, 0xB3); // teal
    let _fg_dim = panic_pack_rgb(fmt, 0x88, 0x88, 0x88); // grey

    // Fill the entire framebuffer with background colour (16/24/32 bpp safe).
    unsafe {
        let bytes_per_pixel = ((fmt >> 32) as u16 / 8) as usize;
        if bytes_per_pixel == 4 {
            let fill = bg_bg;
            for row in 0..h {
                for col in 0..w {
                    core::ptr::write_volatile(
                        fb.add(row * pitch + col * bytes_per_pixel) as *mut u32,
                        fill,
                    );
                }
            }
        } else if bytes_per_pixel == 3 {
            let fill = bg_bg;
            for row in 0..h {
                for col in 0..w {
                    let offset = row * pitch + col * bytes_per_pixel;
                    core::ptr::write_volatile(fb.add(offset) as *mut u8, fill as u8);
                    core::ptr::write_volatile(fb.add(offset + 1) as *mut u8, (fill >> 8) as u8);
                    core::ptr::write_volatile(fb.add(offset + 2) as *mut u8, (fill >> 16) as u8);
                }
            }
        } else if bytes_per_pixel == 2 {
            // 16bpp (e.g. RGB565) : pack fill as 16-bit value
            let r = ((bg_bg >> 16) & 0xFF) as u16;
            let g = ((bg_bg >> 8) & 0xFF) as u16;
            let b = (bg_bg & 0xFF) as u16;
            let fill16 = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
            for row in 0..h {
                for col in 0..w {
                    let offset = row * pitch + col * bytes_per_pixel;
                    core::ptr::write_volatile(fb.add(offset) as *mut u8, fill16 as u8);
                    core::ptr::write_volatile(fb.add(offset + 1) as *mut u8, (fill16 >> 8) as u8);
                }
            }
        }
    }

    let line_h = 16;
    let margin_x = 8;
    let margin_y = 8;
    let max_x = w.saturating_sub(margin_x);

    for (i, &line) in lines.iter().enumerate().take(PANIC_SCREEN_MAX_LINES) {
        let y = margin_y + i * line_h;
        let fg = if i == 0 {
            fg_title
        } else if line.starts_with("!!") || line.starts_with("PANIC") {
            fg_err
        } else {
            fg_txt
        };
        panic_draw_str(fb, pitch, margin_x, y, line, fg, bg_bg, fmt, max_x);
    }
}
