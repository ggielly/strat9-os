/// One device returned by enumeration.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PciDeviceInfo {
    pub address: PciAddress,
    pub vendor_id: u16,
    pub device_id: u16,
    pub class_code: u32,
    pub header_type: u8,
    pub interrupt_pin: u8,
    pub interrupt_line: u8,
}

/// The guest-visible PCI host bridge with configuration mechanism #1.
#[derive(Debug, Clone)]
pub struct PciHostBridge {
    functions: Vec<PciFunction>,
    routing: Routing,
    memory_map: MemoryMap,
    config_address: u32,
}

impl PciHostBridge {
    /// Creates the bridge with only the host bridge function at `0:0.0`.
    pub fn new() -> Self {
        let mut bridge = Self {
            functions: Vec::new(),
            routing: Routing::legacy_default(),
            memory_map: MemoryMap::new(),
            config_address: 0,
        };
        bridge
            .add_function(PciFunction::new_host_bridge(
                PciAddress::bus0(0, 0).expect("bus 0 device 0 is valid"),
            ))
            .expect("host bridge function is unique");
        bridge
    }

    /// Adds one function, updating the multifunction bits and the memory map.
    pub fn add_function(&mut self, function: PciFunction) -> Result<(), PciError> {
        if !function.address().is_modelled() {
            return Err(PciError::NoDevice);
        }
        if self.function(function.address()).is_some() {
            return Err(PciError::DuplicateFunction);
        }
        let address = function.address();
        self.functions.push(function);
        self.functions.sort_by_key(PciFunction::address);
        self.update_multifunction(address.device);
        self.refresh_memory_map();
        Ok(())
    }

    /// Adds a virtio function at `slot` function 0 with the default INTA
    /// interrupt line from the routing table.
    pub fn add_virtio(&mut self, slot: u8, device_type: u8) -> Result<PciAddress, PciError> {
        let address = PciAddress::bus0(slot, 0)?;
        let mut function = PciFunction::new_virtio(address, device_type)?;
        let line = self.routing.gsi(address.device, 1).unwrap_or(PIRQ_GSI_BASE);
        function.config.write_u8(config::INTERRUPT_LINE, line);
        self.add_function(function)?;
        Ok(address)
    }

    /// Looks up a function by address.
    pub fn function(&self, address: PciAddress) -> Option<&PciFunction> {
        self.functions
            .iter()
            .find(|function| function.address() == address)
    }

    /// Mutable lookup by address.
    pub fn function_mut(&mut self, address: PciAddress) -> Option<&mut PciFunction> {
        self.functions
            .iter_mut()
            .find(|function| function.address() == address)
    }

    /// Virtio device at an address, if the function is a virtio one.
    pub fn virtio(&self, address: PciAddress) -> Option<&VirtioPciDevice> {
        self.function(address)?.virtio()
    }

    /// Mutable virtio device at an address.
    pub fn virtio_mut(&mut self, address: PciAddress) -> Option<&mut VirtioPciDevice> {
        self.function_mut(address)?.virtio_mut()
    }

    /// Routing table.
    pub fn routing(&self) -> &Routing {
        &self.routing
    }

    /// Mutable routing table (firmware programming).
    pub fn routing_mut(&mut self) -> &mut Routing {
        &mut self.routing
    }

    /// Current memory BAR placements.
    pub fn memory_map(&self) -> &MemoryMap {
        &self.memory_map
    }

    /// Enumerated functions, sorted by address.
    pub fn enumerate(&self) -> Vec<PciDeviceInfo> {
        self.functions
            .iter()
            .map(|function| PciDeviceInfo {
                address: function.address(),
                vendor_id: function.vendor_id(),
                device_id: function.device_id(),
                class_code: function.class_code(),
                header_type: function.header_type(),
                interrupt_pin: function.interrupt_pin(),
                interrupt_line: function.interrupt_line(),
            })
            .collect()
    }

    /// Direct configuration read (address form, bypassing the CAM latch).
    pub fn config_read(&self, address: PciAddress, offset: u16, size: u8) -> Option<u32> {
        self.function(address)?.read_config(offset, size)
    }

    /// Direct configuration write (address form, bypassing the CAM latch).
    pub fn config_write(&mut self, address: PciAddress, offset: u16, size: u8, value: u32) -> bool {
        let Some(function) = self.function_mut(address) else {
            return false;
        };
        if function.write_config(offset, size, value).is_err() {
            return false;
        }
        self.refresh_memory_map();
        true
    }

    /// Configuration mechanism #1 read for ports `0xCF8..=0xCFF`.
    pub fn io_read(&mut self, port: u16, size: u8) -> Option<u32> {
        let size = size as usize;
        if !matches!(size, 1 | 2 | 4) {
            return None;
        }
        if port >= CONFIG_ADDRESS && port.checked_add(size as u16)? <= CONFIG_ADDRESS + 4 {
            let shift = 8 * (port - CONFIG_ADDRESS) as u32;
            let mask = mask_for_size(size as u8)?;
            return Some((self.config_address >> shift) & mask);
        }
        if port >= CONFIG_DATA && port.checked_add(size as u16)? <= CONFIG_DATA + 4 {
            let decoded = ConfigAddress::decode(self.config_address);
            let Some(decoded) = decoded else {
                return Some(mask_for_size(size as u8)?);
            };
            let offset = decoded.offset + (port - CONFIG_DATA);
            if offset as usize + size > CONFIG_SPACE_SIZE {
                return Some(mask_for_size(size as u8)?);
            }
            return Some(
                self.config_read(decoded.address, offset, size as u8)
                    .unwrap_or_else(|| mask_for_size(size as u8).unwrap_or(0)),
            );
        }
        None
    }

    /// Configuration mechanism #1 write for ports `0xCF8..=0xCFF`.
    pub fn io_write(&mut self, port: u16, size: u8, value: u32) -> bool {
        let size = size as usize;
        if !matches!(size, 1 | 2 | 4) {
            return false;
        }
        if port >= CONFIG_ADDRESS
            && port
                .checked_add(size as u16)
                .is_some_and(|end| end <= CONFIG_ADDRESS + 4)
        {
            let shift = 8 * (port - CONFIG_ADDRESS) as u32;
            let mask = mask_for_size(size as u8).unwrap_or(0);
            self.config_address =
                (self.config_address & !(mask << shift)) | ((value & mask) << shift);
            return true;
        }
        if port >= CONFIG_DATA
            && port
                .checked_add(size as u16)
                .is_some_and(|end| end <= CONFIG_DATA + 4)
        {
            let Some(decoded) = ConfigAddress::decode(self.config_address) else {
                return false;
            };
            let offset = decoded.offset + (port - CONFIG_DATA);
            if offset as usize + size > CONFIG_SPACE_SIZE {
                return false;
            }
            return self.config_write(decoded.address, offset, size as u8, value);
        }
        false
    }

    /// The latched configuration address register value.
    pub fn config_address(&self) -> u32 {
        self.config_address
    }

    /// Resolves a guest physical address through the memory map and reads from
    /// the owning function BAR.
    pub fn mmio_read(&mut self, gpa: u64, size: u8) -> Option<u32> {
        if !matches!(size, 1 | 2 | 4) {
            return None;
        }
        let window = *self.memory_map.find(gpa)?;
        let offset = gpa - window.base;
        if offset + u64::from(size) > window.size {
            return None;
        }
        self.function_mut(window.address)?
            .mmio_read(window.bar, offset, size)
    }

    /// Resolves a guest physical address through the memory map and writes to
    /// the owning function BAR.
    pub fn mmio_write(&mut self, gpa: u64, size: u8, value: u32) -> bool {
        if !matches!(size, 1 | 2 | 4) {
            return false;
        }
        let Some(window) = self.memory_map.find(gpa).copied() else {
            return false;
        };
        let offset = gpa - window.base;
        if offset + u64::from(size) > window.size {
            return false;
        }
        let Some(function) = self.function_mut(window.address) else {
            return false;
        };
        function.mmio_write(window.bar, offset, size, value)
    }

    /// Recomputes the BAR window table (called after any BAR change).
    fn refresh_memory_map(&mut self) {
        let mut windows = Vec::new();
        for function in &self.functions {
            for index in 0..6u8 {
                let Some(bar) = function.bar(index) else {
                    continue;
                };
                if bar.kind() == BarKind::Io || !bar.programmed() {
                    continue;
                }
                windows.push(BarWindow {
                    base: bar.address(),
                    size: bar.size(),
                    address: function.address(),
                    bar: index,
                    prefetchable: bar.prefetchable(),
                });
            }
        }
        windows.sort_by_key(|window| window.base);
        self.memory_map = MemoryMap { windows };
    }

    /// Recomputes the multifunction header bit for every function of one
    /// device slot.
    fn update_multifunction(&mut self, device: u8) {
        let count = self
            .functions
            .iter()
            .filter(|function| function.address().device == device)
            .count();
        for function in self
            .functions
            .iter_mut()
            .filter(|function| function.address().device == device)
        {
            function.set_multifunction(count > 1);
        }
    }
}

impl Default for PciHostBridge {
    fn default() -> Self {
        Self::new()
    }
}
