/// Errors of the PCI model.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PciError {
    /// The requested access has an unsupported size (only 1, 2 and 4 bytes).
    InvalidSize,
    /// The offset plus size falls outside the register/configuration space.
    OutOfBounds,
    /// No function is present at the requested address.
    NoDevice,
    /// A function already exists at the requested address.
    DuplicateFunction,
    /// The BAR definition is invalid (size, kind or index).
    InvalidBar,
    /// The BAR slot is already used.
    BarInUse,
    /// The queue selection does not designate a valid queue.
    InvalidQueue,
    /// The queue size is not a power of two within the supported range.
    InvalidQueueSize,
    /// The queue cannot be enabled before size and addresses are programmed.
    QueueNotReady,
    /// The guest selected a device feature the device does not offer.
    UnsupportedFeature,
    /// The register is read-only.
    ReadOnly,
    /// The written value is not valid for this register.
    InvalidValue,
}

impl PciError {
    /// Stable short description used by the engine logs.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::InvalidSize => "invalid access size",
            Self::OutOfBounds => "access outside the register space",
            Self::NoDevice => "no PCI function at this address",
            Self::DuplicateFunction => "duplicate PCI function",
            Self::InvalidBar => "invalid BAR definition",
            Self::BarInUse => "BAR slot already in use",
            Self::InvalidQueue => "invalid virtio queue",
            Self::InvalidQueueSize => "invalid virtio queue size",
            Self::QueueNotReady => "virtio queue not ready",
            Self::UnsupportedFeature => "unsupported virtio feature",
            Self::ReadOnly => "read-only register",
            Self::InvalidValue => "invalid register value",
        }
    }
}

