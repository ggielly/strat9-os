//! s9vm — guest-visible PCI host bridge (pure model).
//!
//! The guest discovers and drives its virtual devices through a conventional
//! PCI host bridge: configuration mechanism #1 on ports [`CONFIG_ADDRESS`] and
//! [`CONFIG_DATA`], 256-byte configuration spaces, programmable BARs, a
//! firmware-style PIRQ routing table, capability lists (MSI, MSI-X) and the
//! modern virtio PCI transport (five vendor capabilities + common
//! configuration). The engine resolves guest MMIO through [`MemoryMap`] and
//! forwards accesses with [`PciHostBridge::mmio_read`] /
//! [`PciHostBridge::mmio_write`].
//!
//! The module is pure and host-tested: no allocation is performed while
//! servicing an access (configurations, window tables and capability lists are
//! built at construction time; only probe-time growth uses `Vec`).
//!
//! Design decisions:
//! - Only configuration mechanism #1 (Camera Access Method, CAM) is modelled;
//!   there is no ECAM and no PCI-to-PCI bridge, so all devices live on bus 0.
//! - The host bridge is device 0 function 0 (`vendor 0x8086`, `device 0x1237`,
//!   class `0x060000`, header type 0); the identifiers are conventional PCI
//!   data, not vendor branding.
//! - Virtio functions use the modern transport with vendor `0x1AF4` and device
//!   `0x1040 + type` (net = 1, block = 2, console = 3) and a single 64-bit
//!   memory BAR (32 KiB) holding the common, ISR, notify, device and PCI
//!   configuration windows.
//! - MSI/MSI-X are discovered (capabilities + MSI-X table/PBA fields) but never
//!   enabled: no message is generated by this model.

