/// One 256-byte PCI configuration space with byte-lane merging.
#[derive(Debug, Clone)]
pub struct PciConfigSpace {
    bytes: [u8; CONFIG_SPACE_SIZE],
}

impl PciConfigSpace {
    /// Zeroed configuration space.
    pub const fn new() -> Self {
        Self {
            bytes: [0u8; CONFIG_SPACE_SIZE],
        }
    }

    /// Raw bytes of the configuration space.
    pub const fn bytes(&self) -> &[u8; CONFIG_SPACE_SIZE] {
        &self.bytes
    }

    /// Reads 1, 2 or 4 bytes, merging the addressed byte lanes.
    pub fn read(&self, offset: u16, size: u8) -> Option<u32> {
        let size = size as usize;
        if !matches!(size, 1 | 2 | 4) {
            return None;
        }
        let start = offset as usize;
        if start + size > CONFIG_SPACE_SIZE {
            return None;
        }
        let mut value = 0u32;
        for (index, byte) in self.bytes[start..start + size].iter().enumerate() {
            value |= u32::from(*byte) << (8 * index);
        }
        Some(value)
    }

    /// Writes 1, 2 or 4 bytes, merging the addressed byte lanes.
    pub fn write(&mut self, offset: u16, size: u8, value: u32) -> bool {
        let size = size as usize;
        if !matches!(size, 1 | 2 | 4) {
            return false;
        }
        let start = offset as usize;
        if start + size > CONFIG_SPACE_SIZE {
            return false;
        }
        for index in 0..size {
            self.bytes[start + index] = (value >> (8 * index)) as u8;
        }
        true
    }

    /// Convenience: 32-bit read at a dword-aligned offset.
    pub fn read_u32(&self, offset: u16) -> u32 {
        self.read(offset, 4).unwrap_or(0)
    }

    /// Convenience: 32-bit write at a dword-aligned offset.
    pub fn write_u32(&mut self, offset: u16, value: u32) {
        self.write(offset, 4, value);
    }

    /// Convenience: 16-bit read.
    pub fn read_u16(&self, offset: u16) -> u16 {
        self.read(offset, 2).unwrap_or(0) as u16
    }

    /// Convenience: 16-bit write.
    pub fn write_u16(&mut self, offset: u16, value: u16) {
        self.write(offset, 2, u32::from(value));
    }

    /// Convenience: byte read.
    pub fn read_u8(&self, offset: u16) -> u8 {
        self.read(offset, 1).unwrap_or(0) as u8
    }

    /// Convenience: byte write.
    pub fn write_u8(&mut self, offset: u16, value: u8) {
        self.write(offset, 1, u32::from(value));
    }
}

impl Default for PciConfigSpace {
    fn default() -> Self {
        Self::new()
    }
}

