/// Kind of a base address register.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BarKind {
    /// 32-bit memory BAR.
    Memory32,
    /// 64-bit memory BAR (consumes two BAR slots).
    Memory64,
    /// I/O BAR.
    Io,
}

/// Main memory BAR than can be prefetched.
const BAR_FLAG_PREFETCH: u32 = 0x08;
/// Memory BAR type bits for a 64-bit BAR.
const BAR_FLAG_MEMORY_64: u32 = 0x04;
/// I/O BAR type bit.
const BAR_FLAG_IO: u32 = 0x01;

/// One base address register and its programming state.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Bar {
    index: u8,
    kind: BarKind,
    size: u64,
    address: u64,
    prefetchable: bool,
    probe_low: bool,
    probe_high: bool,
}

impl Bar {
    /// Creates a BAR; `size` must be a power of two at least 16 bytes (memory)
    /// or between 4 and 256 bytes (I/O).
    pub fn new(index: u8, kind: BarKind, size: u64, prefetchable: bool) -> Result<Self, PciError> {
        if index >= 6 {
            return Err(PciError::InvalidBar);
        }
        if kind == BarKind::Memory64 && index >= 5 {
            return Err(PciError::InvalidBar);
        }
        if kind == BarKind::Io {
            if size < 4 || size > 256 || !size.is_power_of_two() {
                return Err(PciError::InvalidBar);
            }
        } else if size < 16 || !size.is_power_of_two() {
            return Err(PciError::InvalidBar);
        }
        Ok(Self {
            index,
            kind,
            size,
            address: 0,
            prefetchable,
            probe_low: false,
            probe_high: false,
        })
    }

    pub const fn index(&self) -> u8 {
        self.index
    }

    pub const fn kind(&self) -> BarKind {
        self.kind
    }

    pub const fn size(&self) -> u64 {
        self.size
    }

    pub const fn address(&self) -> u64 {
        self.address
    }

    pub const fn prefetchable(&self) -> bool {
        self.prefetchable
    }

    /// The guest has written all-ones to probe the size.
    pub const fn is_probing(&self) -> bool {
        self.probe_low || self.probe_high
    }

    /// The BAR has a usable address (zero means unassigned) and is not being
    /// probed.
    pub const fn programmed(&self) -> bool {
        self.address != 0 && !self.probe_low && !self.probe_high
    }

    /// Type/flag bits returned in the low dword.
    const fn type_bits(&self) -> u32 {
        let kind_bits = match self.kind {
            BarKind::Memory32 => 0,
            BarKind::Memory64 => BAR_FLAG_MEMORY_64,
            BarKind::Io => BAR_FLAG_IO,
        };
        kind_bits
            | if self.prefetchable {
                BAR_FLAG_PREFETCH
            } else {
                0
            }
    }

    /// Size mask returned while probing the low dword.
    fn mask_low(&self) -> u32 {
        let mask = (!(self.size - 1)) as u32;
        if self.kind == BarKind::Io {
            (mask & 0xFFFF_FFFC) | self.type_bits()
        } else {
            (mask & 0xFFFF_FFF0) | self.type_bits()
        }
    }

    /// Size mask returned while probing the high dword of a 64-bit BAR.
    const fn mask_high(&self) -> u32 {
        (!(self.size - 1) >> 32) as u32
    }

    /// Low dword as read through configuration space.
    pub fn low_dword(&self) -> u32 {
        if self.probe_low {
            return self.mask_low();
        }
        let low = self.address as u32;
        (low & 0xFFFF_FFF0) | self.type_bits()
    }

    /// High dword as read through configuration space (0 for non-64-bit BARs).
    pub fn high_dword(&self) -> u32 {
        if self.kind != BarKind::Memory64 {
            return 0;
        }
        if self.probe_high {
            return self.mask_high();
        }
        (self.address >> 32) as u32
    }

    /// Handles a write to the low dword: all-ones starts a size probe, any
    /// other value programs the address (aligned down to the BAR size).
    pub fn write_low(&mut self, value: u32) {
        if value == 0xFFFF_FFFF {
            self.probe_low = true;
            self.probe_high = false;
            self.address = 0;
            return;
        }
        self.probe_low = false;
        self.probe_high = false;
        let preserved_high = match self.kind {
            BarKind::Memory64 => self.address & 0xFFFF_FFFF_0000_0000,
            _ => 0,
        };
        let low = u64::from(value & 0xFFFF_FFF0);
        self.address = (preserved_high | low) & !(self.size - 1);
    }

    /// Handles a write to the high dword of a 64-bit BAR.
    pub fn write_high(&mut self, value: u32) {
        if self.kind != BarKind::Memory64 {
            return;
        }
        if value == 0xFFFF_FFFF {
            self.probe_high = true;
            return;
        }
        self.probe_high = false;
        let high = u64::from(value) << 32;
        self.address = ((self.address & 0x0000_0000_FFFF_FFFF) | high) & !(self.size - 1);
    }
}

