/// What a PCI function implements.
#[derive(Debug, Clone)]
pub enum FunctionKind {
    HostBridge,
    Virtio(VirtioPciDevice),
}

/// One PCI function: configuration space, BARs and optional device model.
#[derive(Debug, Clone)]
pub struct PciFunction {
    address: PciAddress,
    config: PciConfigSpace,
    bars: [Option<Bar>; 6],
    kind: FunctionKind,
}

impl PciFunction {
    /// Generic function skeleton (no BAR, no capability list).
    pub fn new(address: PciAddress, vendor_id: u16, device_id: u16, class_code: u32) -> Self {
        let mut config = PciConfigSpace::new();
        config.write_u16(config::VENDOR_ID, vendor_id);
        config.write_u16(config::DEVICE_ID, device_id);
        config.write_u8(config::REVISION, 0);
        config.write_u8(config::PROG_IF, (class_code & 0xFF) as u8);
        config.write_u8(config::SUBCLASS, ((class_code >> 8) & 0xFF) as u8);
        config.write_u8(config::CLASS, ((class_code >> 16) & 0xFF) as u8);
        config.write_u8(config::HEADER_TYPE, 0);
        Self {
            address,
            config,
            bars: [None; 6],
            kind: FunctionKind::HostBridge,
        }
    }

    /// Host bridge function (`0:0.0` by convention).
    pub fn new_host_bridge(address: PciAddress) -> Self {
        let mut function = Self::new(
            address,
            HOST_BRIDGE_VENDOR_ID,
            HOST_BRIDGE_DEVICE_ID,
            class_code::HOST_BRIDGE,
        );
        function.kind = FunctionKind::HostBridge;
        function
    }

    /// Modern virtio PCI function: 64-bit memory BAR 0 with the five
    /// transport windows, MSI and MSI-X capabilities, INTA.
    pub fn new_virtio(address: PciAddress, device_type: u8) -> Result<Self, PciError> {
        let mut device = VirtioPciDevice::new(device_type)?;
        let mut function = Self::new(
            address,
            VIRTIO_VENDOR_ID,
            VIRTIO_MODERN_DEVICE_ID_BASE + u16::from(device_type),
            class_code::VIRTIO,
        );
        function.config.write_u8(config::INTERRUPT_PIN, 1);
        function.bars[0] = Some(Bar::new(0, BarKind::Memory64, VIRTIO_BAR_SIZE, false)?);
        install_virtio_capabilities(&mut function, &mut device)?;
        function.kind = FunctionKind::Virtio(device);
        Ok(function)
    }

    pub fn address(&self) -> PciAddress {
        self.address
    }

    pub fn config_space(&self) -> &PciConfigSpace {
        &self.config
    }

    pub const fn kind(&self) -> &FunctionKind {
        &self.kind
    }

    /// Mutable access to the virtio device, if this function is one.
    pub fn virtio(&self) -> Option<&VirtioPciDevice> {
        match &self.kind {
            FunctionKind::Virtio(device) => Some(device),
            FunctionKind::HostBridge => None,
        }
    }

    /// Mutable access to the virtio device, if this function is one.
    pub fn virtio_mut(&mut self) -> Option<&mut VirtioPciDevice> {
        match &mut self.kind {
            FunctionKind::Virtio(device) => Some(device),
            FunctionKind::HostBridge => None,
        }
    }

    pub fn vendor_id(&self) -> u16 {
        self.config.read_u16(config::VENDOR_ID)
    }

    pub fn device_id(&self) -> u16 {
        self.config.read_u16(config::DEVICE_ID)
    }

    pub fn class_code(&self) -> u32 {
        u32::from(self.config.read_u8(config::PROG_IF))
            | (u32::from(self.config.read_u8(config::SUBCLASS)) << 8)
            | (u32::from(self.config.read_u8(config::CLASS)) << 16)
    }

    pub fn header_type(&self) -> u8 {
        self.config.read_u8(config::HEADER_TYPE)
    }

    pub fn command(&self) -> u16 {
        self.config.read_u16(config::COMMAND)
    }

    pub fn status(&self) -> u16 {
        self.config.read_u16(config::STATUS)
    }

    pub fn interrupt_line(&self) -> u8 {
        self.config.read_u8(config::INTERRUPT_LINE)
    }

    pub fn interrupt_pin(&self) -> u8 {
        self.config.read_u8(config::INTERRUPT_PIN)
    }

    /// Programs the BAR slot directly (construction/tests only).
    pub fn install_bar(&mut self, bar: Bar) -> Result<(), PciError> {
        let index = usize::from(bar.index());
        if self.bars[index].is_some() {
            return Err(PciError::BarInUse);
        }
        self.bars[index] = Some(bar);
        Ok(())
    }

    /// Installs a memory BAR at `index`.
    pub fn add_memory_bar(
        &mut self,
        index: u8,
        size: u64,
        kind: BarKind,
        prefetchable: bool,
    ) -> Result<(), PciError> {
        self.install_bar(Bar::new(index, kind, size, prefetchable)?)
    }

    /// Installs an I/O BAR at `index`.
    pub fn add_io_bar(&mut self, index: u8, size: u64) -> Result<(), PciError> {
        self.install_bar(Bar::new(index, BarKind::Io, size, false)?)
    }

    /// Sets the multifunction bit of the header type.
    pub(crate) fn set_multifunction(&mut self, multifunction: bool) {
        let mut header = self.config.read_u8(config::HEADER_TYPE) & 0x7F;
        if multifunction {
            header |= 0x80;
        }
        self.config.write_u8(config::HEADER_TYPE, header);
    }

    /// BAR currently installed at `index`, if any.
    pub fn bar(&self, index: u8) -> Option<&Bar> {
        self.bars.get(usize::from(index)).and_then(Option::as_ref)
    }

    /// True when the function owns a BAR mapping at `bar` covering `offset`.
    pub fn bar_covers(&self, bar: u8, offset: u64) -> bool {
        self.bar(bar).is_some_and(|b| offset < b.size())
    }

    /// Reads a configuration dword, overlaying BAR probe state.
    pub fn read_config(&self, offset: u16, size: u8) -> Option<u32> {
        if !matches!(size, 1 | 2 | 4) {
            return None;
        }
        if offset as usize + usize::from(size) > CONFIG_SPACE_SIZE {
            return None;
        }
        if size == 4 && offset >= config::BAR0 && offset < config::BAR0 + 24 && offset % 4 == 0 {
            let index = usize::from((offset - config::BAR0) / 4);
            return Some(self.read_bar_dword(index));
        }
        self.config.read(offset, size)
    }

    /// Reads one BAR dword, including the 64-bit high half.
    fn read_bar_dword(&self, index: usize) -> u32 {
        if let Some(bar) = self.bars.get(index).and_then(Option::as_ref) {
            return bar.low_dword();
        }
        if index > 0 {
            if let Some(previous) = self.bars.get(index - 1).and_then(Option::as_ref) {
                if previous.kind() == BarKind::Memory64 {
                    return previous.high_dword();
                }
            }
        }
        0
    }

    /// Writes a configuration register with the standard RO/W1C semantics.
    pub fn write_config(&mut self, offset: u16, size: u8, value: u32) -> Result<(), PciError> {
        if !matches!(size, 1 | 2 | 4) {
            return Err(PciError::InvalidSize);
        }
        if offset as usize + usize::from(size) > CONFIG_SPACE_SIZE {
            return Err(PciError::OutOfBounds);
        }
        // BAR programming (dword writes only).
        if size == 4 && offset >= config::BAR0 && offset < config::BAR0 + 24 {
            let index = usize::from((offset - config::BAR0) / 4);
            if let Some(bar) = self.bars.get_mut(index).and_then(Option::as_mut) {
                bar.write_low(value);
            } else if index > 0 {
                if let Some(previous) = self.bars.get_mut(index - 1).and_then(Option::as_mut) {
                    if previous.kind() == BarKind::Memory64 {
                        previous.write_high(value);
                    }
                }
            }
            return Ok(());
        }
        // Command and status are 16-bit registers that the guest also writes
        // one byte at a time; merge the addressed byte lanes.
        let end = offset + u16::from(size);
        if offset >= config::COMMAND && end <= config::COMMAND + 2 {
            self.config.write(offset, size, value);
            return Ok(());
        }
        if offset >= config::STATUS && end <= config::STATUS + 2 {
            let mut bytes = self.config.read_u16(config::STATUS).to_le_bytes();
            for lane in 0..usize::from(size) {
                let register_byte = (offset + lane as u16) - config::STATUS;
                if register_byte == 0 {
                    // Status bits 0..3 are write-one-to-clear; the rest are
                    // read-only.
                    bytes[0] &= !((value >> (8 * lane)) as u8 & status::W1C_MASK as u8);
                }
            }
            self.config
                .write_u16(config::STATUS, u16::from_le_bytes(bytes));
            return Ok(());
        }
        match (offset, size) {
            (config::INTERRUPT_LINE, 1) => {
                self.config.write_u8(config::INTERRUPT_LINE, value as u8);
                Ok(())
            }
            (config::INTERRUPT_PIN, 1) => Err(PciError::ReadOnly),
            (0x00..=0x0F, _) => Err(PciError::ReadOnly),
            (0x2C..=0x2E, _) => Err(PciError::ReadOnly),
            (config::CAPABILITIES, _) => Err(PciError::ReadOnly),
            (config::EXPANSION_ROM, _) => Err(PciError::ReadOnly),
            _ => {
                if self.config.write(offset, size, value) {
                    Ok(())
                } else {
                    Err(PciError::OutOfBounds)
                }
            }
        }
    }

    /// Walks the raw capability linked list (bounded, loop-safe).
    pub fn capability_headers(&self) -> Vec<CapabilityHeader> {
        let mut headers = Vec::new();
        let mut offset = self.config.read_u8(config::CAPABILITIES);
        let mut guard = 0;
        while offset != 0 && guard < 48 {
            let id = self.config.read_u8(u16::from(offset));
            let next = self.config.read_u8(u16::from(offset) + 1);
            headers.push(CapabilityHeader { offset, id, next });
            offset = next;
            guard += 1;
        }
        headers
    }

    /// Typed capability list of this function.
    pub fn capabilities(&self) -> Vec<Capability> {
        match &self.kind {
            FunctionKind::HostBridge => Vec::new(),
            FunctionKind::Virtio(device) => {
                let mut list = Vec::with_capacity(7);
                for capability in device.virtio_capabilities() {
                    list.push(Capability::Virtio(capability));
                }
                list.push(Capability::Msi(device.msi));
                list.push(Capability::Msix(device.msix));
                list
            }
        }
    }

    /// Finds the virtio capability of one configuration type.
    pub fn virtio_capability(&self, cfg_type: u8) -> Option<VirtioCapability> {
        let device = self.virtio()?;
        device
            .virtio_capabilities()
            .into_iter()
            .find(|capability| capability.cfg_type == cfg_type)
    }

    /// MSI capability, if advertised.
    pub fn msi_capability(&self) -> Option<MsiCapability> {
        self.virtio().map(|device| device.msi)
    }

    /// MSI-X capability, if advertised.
    pub fn msix_capability(&self) -> Option<MsixCapability> {
        self.virtio().map(|device| device.msix)
    }

    /// MMIO read inside one BAR of this function.
    pub fn mmio_read(&mut self, bar: u8, offset: u64, size: u8) -> Option<u32> {
        if !matches!(size, 1 | 2 | 4) {
            return None;
        }
        if !self.bar_covers(bar, offset) {
            return None;
        }
        if bar != 0 {
            return None;
        }
        if offset < u64::from(virtio_window::ISR) {
            let device = self.virtio()?;
            return device.common.read(offset as u16, size);
        }
        if offset < u64::from(virtio_window::NOTIFY) {
            let device = self.virtio_mut()?;
            if size == 1 && offset == u64::from(virtio_window::ISR) {
                return Some(u32::from(device.isr_read()));
            }
            return Some(0);
        }
        if offset < u64::from(virtio_window::DEVICE_CFG) {
            return Some(0);
        }
        if offset < u64::from(virtio_window::PCI_CFG) {
            let device = self.virtio()?;
            return device
                .device_config_read((offset - u64::from(virtio_window::DEVICE_CFG)) as u32, size);
        }
        if offset < u64::from(virtio_window::PCI_CFG + VIRTIO_PCI_CFG_SIZE) {
            let config_offset = (offset - u64::from(virtio_window::PCI_CFG)) as u16;
            if u32::from(config_offset) + u32::from(size) > CONFIG_SPACE_SIZE as u32 {
                return None;
            }
            return self.config.read(config_offset, size);
        }
        // MSI-X table/PBA and the remainder of the BAR are not backed yet.
        if offset < u64::from(virtio_window::MSIX_PBA + VIRTIO_COMMON_SIZE) {
            return Some(0);
        }
        None
    }

    /// MMIO write inside one BAR of this function.
    pub fn mmio_write(&mut self, bar: u8, offset: u64, size: u8, value: u32) -> bool {
        if !matches!(size, 1 | 2 | 4) {
            return false;
        }
        if !self.bar_covers(bar, offset) {
            return false;
        }
        if bar != 0 {
            return false;
        }
        if offset < u64::from(virtio_window::ISR) {
            let device = self.virtio_mut();
            let Some(device) = device else {
                return false;
            };
            return device.common.write(offset as u16, size, value).is_ok();
        }
        if offset < u64::from(virtio_window::NOTIFY) {
            // Interrupt status is read-to-clear only.
            return false;
        }
        if offset < u64::from(virtio_window::DEVICE_CFG) {
            if size != 2 {
                return false;
            }
            let byte_offset = (offset - u64::from(virtio_window::NOTIFY)) as u32;
            if byte_offset % VIRTIO_NOTIFY_OFF_MULTIPLIER != 0 {
                return false;
            }
            let queue = (byte_offset / VIRTIO_NOTIFY_OFF_MULTIPLIER) as u16;
            let Some(device) = self.virtio_mut() else {
                return false;
            };
            device.notify_queue(queue).is_ok()
        } else if offset < u64::from(virtio_window::PCI_CFG) {
            // Device-specific configuration is read-only.
            false
        } else {
            // PCI configuration window and MSI-X tables are read-only here.
            false
        }
    }
}

/// Encodes the five virtio capabilities, MSI and MSI-X into the configuration
/// space, linking them from the capability pointer.
fn install_virtio_capabilities(
    function: &mut PciFunction,
    device: &mut VirtioPciDevice,
) -> Result<(), PciError> {
    let mut next_offset = 0x40u8;
    let mut offsets = [0u8; 5];
    let mut previous: Option<u8> = None;
    for (index, capability) in device.virtio_capabilities().iter().enumerate() {
        let offset = next_offset;
        offsets[index] = offset;
        let next = offset + VIRTIO_CAPABILITY_SIZE as u8;
        encode_virtio_capability(&mut function.config, offset, next, capability);
        if let Some(previous_offset) = previous {
            function
                .config
                .write_u8(u16::from(previous_offset) + 1, offset);
        } else {
            function.config.write_u8(config::CAPABILITIES, offset);
        }
        previous = Some(offset);
        next_offset = next;
    }
    let msi_offset = next_offset;
    let msix_offset = msi_offset + 12;
    encode_msi_capability(&mut function.config, msi_offset, msix_offset, &device.msi);
    encode_msix_capability(&mut function.config, msix_offset, 0, &device.msix);
    if let Some(previous_offset) = previous {
        function
            .config
            .write_u8(u16::from(previous_offset) + 1, msi_offset);
    }
    function.config.write_u8(
        config::STATUS,
        function.config.read_u8(config::STATUS) | (status::CAPABILITIES as u8),
    );
    device.set_capability_offsets(offsets, msi_offset, msix_offset);
    Ok(())
}

/// Encodes one virtio vendor capability structure.
fn encode_virtio_capability(
    config: &mut PciConfigSpace,
    offset: u8,
    next: u8,
    capability: &VirtioCapability,
) {
    let base = u16::from(offset);
    config.write_u8(base, capability_id::VENDOR);
    config.write_u8(base + 1, next);
    config.write_u8(base + 2, VIRTIO_CAPABILITY_SIZE as u8);
    config.write_u8(base + 3, capability.cfg_type);
    config.write_u8(base + 4, capability.bar);
    config.write_u8(base + 5, capability.id);
    config.write_u32(base + 8, capability.mmio_offset);
    config.write_u32(base + 12, capability.length);
}

/// Encodes the MSI capability structure (32-bit message address).
fn encode_msi_capability(
    config: &mut PciConfigSpace,
    offset: u8,
    next: u8,
    capability: &MsiCapability,
) {
    let base = u16::from(offset);
    config.write_u8(base, capability_id::MSI);
    config.write_u8(base + 1, next);
    // Message control: vectors minus one, 32-bit message address, disabled.
    config.write_u16(base + 2, u16::from(capability.vectors.saturating_sub(1)));
    config.write_u32(base + 4, 0);
    config.write_u16(base + 8, 0);
}

/// Encodes the MSI-X capability structure.
fn encode_msix_capability(
    config: &mut PciConfigSpace,
    offset: u8,
    next: u8,
    capability: &MsixCapability,
) {
    let base = u16::from(offset);
    config.write_u8(base, capability_id::MSIX);
    config.write_u8(base + 1, next);
    // Message control: table size minus one, MSI-X disabled.
    config.write_u16(base + 2, capability.table_size.saturating_sub(1));
    config.write_u32(
        base + 4,
        (capability.table_offset & !0x7) | u32::from(capability.table_bar & 0x7),
    );
    config.write_u32(
        base + 8,
        (capability.pba_offset & !0x7) | u32::from(capability.pba_bar & 0x7),
    );
}

