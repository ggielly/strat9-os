/// Capacity reported by the block device configuration, in 512-byte sectors
/// (128 KiB).
pub const BLOCK_CAPACITY_SECTORS: u64 = 256;
/// Console size reported by the console device configuration.
pub const CONSOLE_COLUMNS: u16 = 80;
/// Console rows reported by the console device configuration.
pub const CONSOLE_ROWS: u16 = 24;
/// Default MAC address of the network device (locally administered).
pub const NET_MAC: [u8; 6] = [0x02, 0x00, 0x00, 0x00, 0x00, 0x01];
/// Maximum number of queue notifications kept for the engine.
pub const MAX_PENDING_NOTIFICATIONS: usize = 16;

/// One virtio PCI function: transport windows, common configuration and the
/// device-specific configuration space.
#[derive(Debug, Clone)]
pub struct VirtioPciDevice {
    pub device_type: u8,
    pub common: VirtioCommonConfig,
    pub common_cap: VirtioCapability,
    pub notify_cap: VirtioCapability,
    pub isr_cap: VirtioCapability,
    pub device_cap: VirtioCapability,
    pub pci_cap: VirtioCapability,
    pub msi: MsiCapability,
    pub msix: MsixCapability,
    /// Interrupt status byte; reading ISR returns it and clears it.
    isr: u8,
    /// Queue indices notified by the guest, waiting for the engine.
    notifications: Vec<u16>,
}

impl VirtioPciDevice {
    /// Builds the device for one virtio type with the default transport
    /// layout.
    pub fn new(device_type: u8) -> Result<Self, PciError> {
        let common = VirtioCommonConfig::new(device_type)?;
        let queues = common.num_queues();
        Ok(Self {
            device_type,
            common,
            common_cap: VirtioCapability {
                config_offset: 0,
                cfg_type: virtio_cfg_type::COMMON,
                bar: 0,
                id: 0,
                mmio_offset: virtio_window::COMMON,
                length: VIRTIO_COMMON_SIZE,
            },
            notify_cap: VirtioCapability {
                config_offset: 0,
                cfg_type: virtio_cfg_type::NOTIFY,
                bar: 0,
                id: 0,
                mmio_offset: virtio_window::NOTIFY,
                length: VIRTIO_NOTIFY_SIZE,
            },
            isr_cap: VirtioCapability {
                config_offset: 0,
                cfg_type: virtio_cfg_type::ISR,
                bar: 0,
                id: 0,
                mmio_offset: virtio_window::ISR,
                length: VIRTIO_ISR_SIZE,
            },
            device_cap: VirtioCapability {
                config_offset: 0,
                cfg_type: virtio_cfg_type::DEVICE,
                bar: 0,
                id: 0,
                mmio_offset: virtio_window::DEVICE_CFG,
                length: VIRTIO_DEVICE_CFG_SIZE,
            },
            pci_cap: VirtioCapability {
                config_offset: 0,
                cfg_type: virtio_cfg_type::PCI,
                bar: 0,
                id: 0,
                mmio_offset: virtio_window::PCI_CFG,
                length: VIRTIO_PCI_CFG_SIZE,
            },
            msi: MsiCapability {
                config_offset: 0,
                vectors: queues.min(8) as u8,
                is_64bit: false,
            },
            msix: MsixCapability {
                config_offset: 0,
                table_size: queues + 1,
                table_bar: 0,
                table_offset: MSIX_TABLE_OFFSET,
                pba_bar: 0,
                pba_offset: MSIX_PBA_OFFSET,
            },
            isr: 0,
            notifications: Vec::with_capacity(MAX_PENDING_NOTIFICATIONS),
        })
    }

    /// All five virtio vendor capabilities, in transport order.
    pub fn virtio_capabilities(&self) -> [VirtioCapability; 5] {
        [
            self.common_cap,
            self.notify_cap,
            self.isr_cap,
            self.device_cap,
            self.pci_cap,
        ]
    }

    /// Sets the configuration-space offsets of the capability structures.
    pub(crate) fn set_capability_offsets(&mut self, offsets: [u8; 5], msi: u8, msix: u8) {
        self.common_cap.config_offset = offsets[0];
        self.notify_cap.config_offset = offsets[1];
        self.isr_cap.config_offset = offsets[2];
        self.device_cap.config_offset = offsets[3];
        self.pci_cap.config_offset = offsets[4];
        self.msi.config_offset = msi;
        self.msix.config_offset = msix;
    }

    /// Reads the interrupt status byte, clearing it (read-to-clear).
    pub fn isr_read(&mut self) -> u8 {
        let value = self.isr;
        self.isr = 0;
        value
    }

    /// Raises interrupt status bits (device side, diagnostics/used-ring
    /// completion).
    pub fn raise_isr(&mut self, bits: u8) {
        self.isr |= bits;
    }

    /// Pending interrupt status, without clearing it.
    pub const fn isr_status(&self) -> u8 {
        self.isr
    }

    /// Queue notifications recorded since the last [`Self::take_notifications`].
    pub fn notifications(&self) -> &[u16] {
        &self.notifications
    }

    /// Takes the pending queue notifications.
    pub fn take_notifications(&mut self) -> Vec<u16> {
        core::mem::take(&mut self.notifications)
    }

    /// Handles a 16-bit notify write targeting `queue`.
    pub fn notify_queue(&mut self, queue: u16) -> Result<(), PciError> {
        if queue >= self.common.num_queues {
            return Err(PciError::InvalidQueue);
        }
        let state = self
            .common
            .queues()
            .get(usize::from(queue))
            .ok_or(PciError::InvalidQueue)?;
        if !state.enabled || state.size == 0 {
            return Err(PciError::QueueNotReady);
        }
        if self.notifications.len() < MAX_PENDING_NOTIFICATIONS {
            self.notifications.push(queue);
        }
        Ok(())
    }

    /// Reads a byte (or lane) of the device-specific configuration window.
    pub fn device_config_read(&self, offset: u32, size: u8) -> Option<u32> {
        let size = size as usize;
        if !matches!(size, 1 | 2 | 4) {
            return None;
        }
        let mut bytes = [0u8; 8];
        match self.device_type {
            virtio_device_type::CONSOLE => {
                bytes[..2].copy_from_slice(&CONSOLE_COLUMNS.to_le_bytes());
                bytes[2..4].copy_from_slice(&CONSOLE_ROWS.to_le_bytes());
            }
            virtio_device_type::BLOCK => {
                bytes[..8].copy_from_slice(&BLOCK_CAPACITY_SECTORS.to_le_bytes());
            }
            virtio_device_type::NET => bytes[..6].copy_from_slice(&NET_MAC),
            _ => return None,
        }
        let start = offset as usize;
        if start + size > bytes.len() {
            return None;
        }
        let mut value = 0u32;
        for (index, byte) in bytes[start..start + size].iter().enumerate() {
            value |= u32::from(*byte) << (8 * index);
        }
        Some(value)
    }
}

