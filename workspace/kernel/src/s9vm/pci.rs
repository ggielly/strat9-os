/// Address of one PCI function (bus/device/function).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct PciAddress {
    pub bus: u8,
    pub device: u8,
    pub function: u8,
}

impl PciAddress {
    /// Builds an address; values outside the architectural field widths are
    /// rejected.
    pub fn new(bus: u8, device: u8, function: u8) -> Result<Self, PciError> {
        if device >= DEVICES_PER_BUS || function >= FUNCTIONS_PER_DEVICE {
            return Err(PciError::NoDevice);
        }
        Ok(Self {
            bus,
            device,
            function,
        })
    }

    /// Bus 0 address helper.
    pub fn bus0(device: u8, function: u8) -> Result<Self, PciError> {
        Self::new(0, device, function)
    }

    /// Whether the address belongs to the modelled host bridge (bus 0).
    pub const fn is_modelled(&self) -> bool {
        self.bus <= MAX_BUS
    }
}

/// Decoded configuration mechanism #1 address register.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ConfigAddress {
    pub address: PciAddress,
    /// Register offset, always a multiple of 4 (the CAM selects a dword).
    pub offset: u16,
}

impl ConfigAddress {
    /// Decodes the `0xCF8` register value.
    ///
    /// Returns `None` when the enable bit is clear or when the encoded address
    /// cannot designate a function (bus/device/function fields are always
    /// within range by construction, but the encoding itself is still
    /// validated for round-trip safety).
    pub fn decode(value: u32) -> Option<Self> {
        if value & CONFIG_ADDRESS_ENABLE == 0 {
            return None;
        }
        let bus = ((value >> 16) & 0xFF) as u8;
        let device = ((value >> 11) & 0x1F) as u8;
        let function = ((value >> 8) & 0x07) as u8;
        let register = ((value >> 2) & 0x3F) as u16;
        let address = PciAddress::new(bus, device, function).ok()?;
        Some(Self {
            address,
            offset: register * 4,
        })
    }

    /// Encodes a decoded address back into the `0xCF8` register value.
    pub fn encode(&self) -> u32 {
        CONFIG_ADDRESS_ENABLE
            | ((self.address.bus as u32) << 16)
            | (((self.address.device as u32) & 0x1F) << 11)
            | (((self.address.function as u32) & 0x07) << 8)
            | (((self.offset as u32) / 4) << 2)
    }

    /// Builds the CAM value for one function and dword-aligned offset.
    pub fn raw(address: PciAddress, offset: u16) -> u32 {
        Self {
            address,
            offset: offset & !3,
        }
        .encode()
    }
}

