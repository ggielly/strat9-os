/// First GSI used by the legacy PIRQ routing table.
pub const PIRQ_GSI_BASE: u8 = 16;
/// Number of legacy PIRQ lines.
pub const PIRQ_COUNT: u8 = 4;

/// One legacy interrupt route.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Route {
    pub device: u8,
    pub pin: u8,
    pub gsi: u8,
}

/// Firmware-style `(device, pin) -> GSI` table.
#[derive(Debug, Clone)]
pub struct Routing {
    routes: Vec<Route>,
}

impl Routing {
    /// Empty routing table.
    pub fn new() -> Self {
        Self { routes: Vec::new() }
    }

    /// Default legacy rotation: `gsi = 16 + (device + pin - 1) % 4` for every
    /// device of bus 0 and every pin `INTA..INTD`.
    pub fn legacy_default() -> Self {
        let mut routes = Vec::with_capacity(usize::from(DEVICES_PER_BUS) * 4);
        for device in 0..DEVICES_PER_BUS {
            for pin in 1..=PIRQ_COUNT {
                routes.push(Route {
                    device,
                    pin,
                    gsi: Self::legacy_gsi(device, pin),
                });
            }
        }
        Self { routes }
    }

    /// Legacy rotation formula for one device/pin pair.
    pub fn legacy_gsi(device: u8, pin: u8) -> u8 {
        let pin_index = pin.saturating_sub(1) % PIRQ_COUNT;
        PIRQ_GSI_BASE + ((device % PIRQ_COUNT) + pin_index) % PIRQ_COUNT
    }

    /// Looks up the GSI of a device pin (`pin` is `1..=4`).
    pub fn gsi(&self, device: u8, pin: u8) -> Option<u8> {
        self.routes
            .iter()
            .find(|route| route.device == device && route.pin == pin)
            .map(|route| route.gsi)
    }

    /// Programs a route (firmware side).
    pub fn set(&mut self, device: u8, pin: u8, gsi: u8) -> Result<(), PciError> {
        if pin == 0 || pin > PIRQ_COUNT {
            return Err(PciError::InvalidValue);
        }
        if let Some(route) = self
            .routes
            .iter_mut()
            .find(|route| route.device == device && route.pin == pin)
        {
            route.gsi = gsi;
        } else {
            self.routes.push(Route { device, pin, gsi });
        }
        Ok(())
    }

    /// All programmed routes.
    pub fn routes(&self) -> &[Route] {
        &self.routes
    }
}

impl Default for Routing {
    fn default() -> Self {
        Self::legacy_default()
    }
}

