/// Per-queue state of the virtio common configuration.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct QueueState {
    pub size: u16,
    pub msix_vector: u16,
    pub enabled: bool,
    pub desc: u64,
    pub avail: u64,
    pub used: u64,
}

impl QueueState {
    /// Clears every field (device reset or queue reconfiguration).
    pub fn reset(&mut self) {
        *self = Self::default();
    }

    /// True when desc/avail/used satisfy the modern alignment rules and are
    /// non-zero.
    fn addresses_valid(&self) -> bool {
        self.desc != 0
            && self.desc % 16 == 0
            && self.avail != 0
            && self.avail % 2 == 0
            && self.used != 0
            && self.used % 4 == 0
    }
}

/// Common configuration state machine of one modern virtio PCI function.
#[derive(Debug, Clone)]
pub struct VirtioCommonConfig {
    device_type: u8,
    device_features: u64,
    driver_features: u64,
    msix_config: u16,
    num_queues: u16,
    device_status: u8,
    config_generation: u8,
    queue_select: u16,
    queues: Vec<QueueState>,
}

impl VirtioCommonConfig {
    /// Builds the common configuration for one virtio device type.
    pub fn new(device_type: u8) -> Result<Self, PciError> {
        let (num_queues, features) = match device_type {
            virtio_device_type::NET => (2, virtio_features::VERSION_1 | virtio_features::NET_MAC),
            virtio_device_type::BLOCK => {
                (1, virtio_features::VERSION_1 | virtio_features::BLOCK_RO)
            }
            virtio_device_type::CONSOLE => (
                2,
                virtio_features::VERSION_1 | virtio_features::CONSOLE_SIZE,
            ),
            _ => return Err(PciError::InvalidValue),
        };
        Ok(Self {
            device_type,
            device_features: features,
            driver_features: 0,
            msix_config: MSIX_VECTOR_NONE,
            num_queues,
            device_status: 0,
            config_generation: 0,
            queue_select: 0,
            queues: alloc::vec![QueueState::default(); usize::from(num_queues)],
        })
    }

    pub const fn device_type(&self) -> u8 {
        self.device_type
    }

    pub const fn device_features(&self) -> u64 {
        self.device_features
    }

    pub const fn driver_features(&self) -> u64 {
        self.driver_features
    }

    pub const fn num_queues(&self) -> u16 {
        self.num_queues
    }

    pub const fn device_status(&self) -> u8 {
        self.device_status
    }

    pub const fn config_generation(&self) -> u8 {
        self.config_generation
    }

    pub const fn queue_select(&self) -> u16 {
        self.queue_select
    }

    /// Selected queue, if the selection is valid.
    pub fn selected_queue(&self) -> Option<&QueueState> {
        self.queues.get(usize::from(self.queue_select))
    }

    /// All queue states.
    pub fn queues(&self) -> &[QueueState] {
        &self.queues
    }

    /// Acknowledges the device (driver writes a non-zero status).
    pub fn set_device_status(&mut self, value: u8) {
        if value == 0 {
            self.reset_driver_state();
        } else {
            self.device_status = value;
        }
    }

    /// Full reset of the driver-visible state (status=0 semantics).
    pub fn reset_driver_state(&mut self) {
        self.device_status = 0;
        self.driver_features = 0;
        self.msix_config = MSIX_VECTOR_NONE;
        self.queue_select = 0;
        for queue in &mut self.queues {
            queue.reset();
        }
        self.config_generation = self.config_generation.wrapping_add(1);
    }

    /// Reads one common-configuration register (1, 2 or 4 bytes).
    pub fn read(&self, offset: u16, size: u8) -> Option<u32> {
        // The 8/16-bit registers share their dword with neighbours; build the
        // containing dword and extract the requested byte lanes from it.
        let aligned = offset & !3;
        let value: u64 = match aligned {
            0x00 => self.device_features & 0xFFFF_FFFF,
            0x04 => self.device_features >> 32,
            0x08 => self.driver_features & 0xFFFF_FFFF,
            0x0C => self.driver_features >> 32,
            0x10 => u64::from(self.msix_config) | (u64::from(self.num_queues) << 16),
            0x14 => {
                u64::from(self.device_status)
                    | (u64::from(self.config_generation) << 8)
                    | (u64::from(self.queue_select) << 16)
            }
            common_reg::QUEUE_SIZE => {
                let queue = self.selected_queue()?;
                u64::from(queue.size) | (u64::from(queue.msix_vector) << 16)
            }
            common_reg::QUEUE_ENABLE => {
                let queue = self.selected_queue()?;
                u64::from(u8::from(queue.enabled)) | (u64::from(self.queue_select) << 16)
            }
            common_reg::QUEUE_DESC => self.selected_queue()?.desc & 0xFFFF_FFFF,
            0x24 => self.selected_queue()?.desc >> 32,
            common_reg::QUEUE_AVAIL => self.selected_queue()?.avail & 0xFFFF_FFFF,
            0x2C => self.selected_queue()?.avail >> 32,
            common_reg::QUEUE_USED => self.selected_queue()?.used & 0xFFFF_FFFF,
            0x34 => self.selected_queue()?.used >> 32,
            _ => return None,
        };
        let byte_offset = usize::from(offset - aligned);
        if byte_offset + usize::from(size) > 4 {
            return None;
        }
        let shift = 8 * byte_offset;
        Some(((value >> shift) as u32) & mask_for_size(size)?)
    }

    /// Writes one common-configuration register.
    ///
    /// The modern transport uses 32-bit accesses for the 64-bit registers and
    /// natural-width accesses for the others; anything else fails.
    pub fn write(&mut self, offset: u16, size: u8, value: u32) -> Result<(), PciError> {
        // Every register at or after `QUEUE_SIZE` belongs to the selected
        // queue; a queue write must target a valid selection. Writing
        // `QUEUE_SELECT` itself is always allowed.
        if offset >= common_reg::QUEUE_SIZE && self.selected_queue().is_none() {
            return Err(PciError::InvalidQueue);
        }
        match (offset, size) {
            (common_reg::DEVICE_FEATURE, 4) => Err(PciError::ReadOnly),
            (0x04, 4) => Err(PciError::ReadOnly),
            (common_reg::DRIVER_FEATURE, 4) => self.write_driver_features(value, false),
            (0x0C, 4) => self.write_driver_features(value, true),
            (common_reg::MSIX_CONFIG, 2) => {
                self.msix_config = value as u16;
                Ok(())
            }
            (common_reg::NUM_QUEUES, 2) => Err(PciError::ReadOnly),
            (common_reg::DEVICE_STATUS, 1) => {
                self.set_device_status(value as u8);
                Ok(())
            }
            (common_reg::CONFIG_GENERATION, 1) => Err(PciError::ReadOnly),
            (common_reg::QUEUE_SELECT, 2) => {
                self.queue_select = value as u16;
                Ok(())
            }
            (common_reg::QUEUE_SIZE, 2) => {
                let size = value as u16;
                if size != 0 && (size > QUEUE_MAX_SIZE || !size.is_power_of_two()) {
                    return Err(PciError::InvalidQueueSize);
                }
                let queue = &mut self.queues[usize::from(self.queue_select)];
                queue.size = size;
                // Changing the size invalidates an enabled queue.
                queue.enabled = false;
                Ok(())
            }
            (common_reg::QUEUE_MSIX_VECTOR, 2) => {
                self.queues[usize::from(self.queue_select)].msix_vector = value as u16;
                Ok(())
            }
            (common_reg::QUEUE_ENABLE, 2) => {
                let enable = value as u16;
                if enable > 1 {
                    return Err(PciError::InvalidValue);
                }
                let queue = &mut self.queues[usize::from(self.queue_select)];
                if enable == 1 {
                    if queue.size == 0 || !queue.addresses_valid() {
                        return Err(PciError::QueueNotReady);
                    }
                    queue.enabled = true;
                } else {
                    queue.enabled = false;
                }
                Ok(())
            }
            (common_reg::QUEUE_NOTIFY_OFF, 2) => Err(PciError::ReadOnly),
            (common_reg::QUEUE_DESC, 4) => {
                let queue = &mut self.queues[usize::from(self.queue_select)];
                queue.desc = (queue.desc & 0xFFFF_FFFF_0000_0000) | u64::from(value);
                queue.enabled = false;
                Ok(())
            }
            (0x24, 4) => {
                let queue = &mut self.queues[usize::from(self.queue_select)];
                queue.desc = (queue.desc & 0x0000_0000_FFFF_FFFF) | (u64::from(value) << 32);
                queue.enabled = false;
                Ok(())
            }
            (common_reg::QUEUE_AVAIL, 4) => {
                let queue = &mut self.queues[usize::from(self.queue_select)];
                queue.avail = (queue.avail & 0xFFFF_FFFF_0000_0000) | u64::from(value);
                queue.enabled = false;
                Ok(())
            }
            (0x2C, 4) => {
                let queue = &mut self.queues[usize::from(self.queue_select)];
                queue.avail = (queue.avail & 0x0000_0000_FFFF_FFFF) | (u64::from(value) << 32);
                queue.enabled = false;
                Ok(())
            }
            (common_reg::QUEUE_USED, 4) => {
                let queue = &mut self.queues[usize::from(self.queue_select)];
                queue.used = (queue.used & 0xFFFF_FFFF_0000_0000) | u64::from(value);
                queue.enabled = false;
                Ok(())
            }
            (0x34, 4) => {
                let queue = &mut self.queues[usize::from(self.queue_select)];
                queue.used = (queue.used & 0x0000_0000_FFFF_FFFF) | (u64::from(value) << 32);
                queue.enabled = false;
                Ok(())
            }
            _ => Err(PciError::InvalidValue),
        }
    }

    /// Programs one half of the driver feature word.
    fn write_driver_features(&mut self, value: u32, high: bool) -> Result<(), PciError> {
        let candidate = if high {
            (self.driver_features & 0x0000_0000_FFFF_FFFF) | (u64::from(value) << 32)
        } else {
            (self.driver_features & 0xFFFF_FFFF_0000_0000) | u64::from(value)
        };
        if candidate & !self.device_features != 0 {
            return Err(PciError::UnsupportedFeature);
        }
        self.driver_features = candidate;
        Ok(())
    }
}

/// Mask for a 1/2/4-byte access.
const fn mask_for_size(size: u8) -> Option<u32> {
    match size {
        1 => Some(0xFF),
        2 => Some(0xFFFF),
        4 => Some(0xFFFF_FFFF),
        _ => None,
    }
}

