/// One programmed memory BAR window.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct BarWindow {
    pub base: u64,
    pub size: u64,
    pub address: PciAddress,
    pub bar: u8,
    pub prefetchable: bool,
}

impl BarWindow {
    /// End address (exclusive) of the window.
    pub const fn end(&self) -> u64 {
        self.base + self.size
    }

    /// True when `gpa` falls inside the window.
    pub const fn contains(&self, gpa: u64) -> bool {
        gpa >= self.base && gpa < self.end()
    }
}

/// Current memory BAR placements, used to resolve guest MMIO to devices.
#[derive(Debug, Clone, Default)]
pub struct MemoryMap {
    windows: Vec<BarWindow>,
}

impl MemoryMap {
    /// Empty map.
    pub fn new() -> Self {
        Self::default()
    }

    /// All programmed memory windows, in function/bar order.
    pub fn windows(&self) -> &[BarWindow] {
        &self.windows
    }

    /// Finds the window owning a guest physical address.
    pub fn find(&self, gpa: u64) -> Option<&BarWindow> {
        self.windows.iter().find(|window| window.contains(gpa))
    }

    /// True when a guest physical address is claimed by a device BAR.
    pub fn contains(&self, gpa: u64) -> bool {
        self.find(gpa).is_some()
    }
}

