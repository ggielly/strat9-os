const RCON: [u8; 10] = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36];

/// AES-128 key schedule + block cipher.
#[derive(Clone)]
pub struct Aes128 {
    round_keys: [[u8; 16]; 11],
}

impl Aes128 {
    pub fn new(key: &[u8; 16]) -> Self {
        let mut rk = [[0u8; 16]; 11];
        rk[0] = *key;
        for round in 1..11 {
            let prev = rk[round - 1];
            // Rotate last word, substitute, add round constant.
            let mut t = [prev[13], prev[14], prev[15], prev[12]];
            for b in t.iter_mut() {
                *b = SBOX[*b as usize];
            }
            t[0] ^= RCON[round - 1];
            for i in 0..4 {
                rk[round][i] = prev[i] ^ t[i];
            }
            for i in 4..16 {
                rk[round][i] = prev[i] ^ rk[round][i - 4];
            }
        }
        Self { round_keys: rk }
    }

    pub fn encrypt_block(&self, block: &mut [u8; 16]) {
        add_round_key(block, &self.round_keys[0]);
        for round in 1..10 {
            sub_bytes(block);
            shift_rows(block);
            mix_columns(block);
            add_round_key(block, &self.round_keys[round]);
        }
        sub_bytes(block);
        shift_rows(block);
        add_round_key(block, &self.round_keys[10]);
    }

    pub fn decrypt_block(&self, block: &mut [u8; 16]) {
        add_round_key(block, &self.round_keys[10]);
        for round in (1..10).rev() {
            inv_shift_rows(block);
            inv_sub_bytes(block);
            add_round_key(block, &self.round_keys[round]);
            inv_mix_columns(block);
        }
        inv_shift_rows(block);
        inv_sub_bytes(block);
        add_round_key(block, &self.round_keys[0]);
    }
}

fn add_round_key(s: &mut [u8; 16], k: &[u8; 16]) {
    for i in 0..16 {
        s[i] ^= k[i];
    }
}

fn sub_bytes(s: &mut [u8; 16]) {
    for b in s.iter_mut() {
        *b = SBOX[*b as usize];
    }
}

fn inv_sub_bytes(s: &mut [u8; 16]) {
    for b in s.iter_mut() {
        *b = INV_SBOX[*b as usize];
    }
}

fn shift_rows(s: &mut [u8; 16]) {
    // State is column-major: index = column * 4 + row.
    let t = *s;
    s[0] = t[0];
    s[1] = t[5];
    s[2] = t[10];
    s[3] = t[15];
    s[4] = t[4];
    s[5] = t[9];
    s[6] = t[14];
    s[7] = t[3];
    s[8] = t[8];
    s[9] = t[13];
    s[10] = t[2];
    s[11] = t[7];
    s[12] = t[12];
    s[13] = t[1];
    s[14] = t[6];
    s[15] = t[11];
}

fn inv_shift_rows(s: &mut [u8; 16]) {
    let t = *s;
    s[0] = t[0];
    s[1] = t[13];
    s[2] = t[10];
    s[3] = t[7];
    s[4] = t[4];
    s[5] = t[1];
    s[6] = t[14];
    s[7] = t[11];
    s[8] = t[8];
    s[9] = t[5];
    s[10] = t[2];
    s[11] = t[15];
    s[12] = t[12];
    s[13] = t[9];
    s[14] = t[6];
    s[15] = t[3];
}

fn xtime(x: u8) -> u8 {
    (x << 1) ^ (0x1b & (0u8.wrapping_sub(x >> 7)))
}

fn mix_columns(s: &mut [u8; 16]) {
    for c in 0..4 {
        let i = c * 4;
        let a0 = s[i];
        let a1 = s[i + 1];
        let a2 = s[i + 2];
        let a3 = s[i + 3];
        s[i] = xtime(a0) ^ (xtime(a1) ^ a1) ^ a2 ^ a3;
        s[i + 1] = a0 ^ xtime(a1) ^ (xtime(a2) ^ a2) ^ a3;
        s[i + 2] = a0 ^ a1 ^ xtime(a2) ^ (xtime(a3) ^ a3);
        s[i + 3] = (xtime(a0) ^ a0) ^ a1 ^ a2 ^ xtime(a3);
    }
}

fn mul(a: u8, b: u8) -> u8 {
    let mut res = 0u8;
    let mut x = a;
    let mut y = b;
    while y != 0 {
        if y & 1 != 0 {
            res ^= x;
        }
        x = xtime(x);
        y >>= 1;
    }
    res
}

fn inv_mix_columns(s: &mut [u8; 16]) {
    for c in 0..4 {
        let i = c * 4;
        let a0 = s[i];
        let a1 = s[i + 1];
        let a2 = s[i + 2];
        let a3 = s[i + 3];
        s[i] = mul(a0, 0x0e) ^ mul(a1, 0x0b) ^ mul(a2, 0x0d) ^ mul(a3, 0x09);
        s[i + 1] = mul(a0, 0x09) ^ mul(a1, 0x0e) ^ mul(a2, 0x0b) ^ mul(a3, 0x0d);
        s[i + 2] = mul(a0, 0x0d) ^ mul(a1, 0x09) ^ mul(a2, 0x0e) ^ mul(a3, 0x0b);
        s[i + 3] = mul(a0, 0x0b) ^ mul(a1, 0x0d) ^ mul(a2, 0x09) ^ mul(a3, 0x0e);
    }
}

/// Encrypt one block with AES-128.
pub fn aes128_encrypt_block(key: &[u8; 16], block: &mut [u8; 16]) {
    Aes128::new(key).encrypt_block(block);
}

/// Decrypt one block with AES-128.
pub fn aes128_decrypt_block(key: &[u8; 16], block: &mut [u8; 16]) {
    Aes128::new(key).decrypt_block(block);
}

/// NIST AES key unwrap (RFC 3394) used for encrypted EAPOL-Key data.
///
/// `wrapped.len()` must be a multiple of 8 and at least 24.  Returns the
/// unwrapped key length on success.
pub fn key_unwrap(kek: &[u8; 16], wrapped: &[u8], out: &mut [u8]) -> Option<usize> {
    if wrapped.len() < 24 || wrapped.len() % 8 != 0 {
        return None;
    }
    let n = wrapped.len() / 8 - 1;
    if out.len() < n * 8 {
        return None;
    }
    let cipher = Aes128::new(kek);
    let mut a = [0u8; 8];
    a.copy_from_slice(&wrapped[..8]);
    out[..n * 8].copy_from_slice(&wrapped[8..]);
    for j in (0..6).rev() {
        for i in (0..n).rev() {
            let t = (n * j + i + 1) as u64;
            let mut block = [0u8; 16];
            for k in 0..8 {
                block[k] = a[k] ^ ((t >> (8 * (7 - k))) & 0xff) as u8;
            }
            block[8..].copy_from_slice(&out[i * 8..i * 8 + 8]);
            cipher.decrypt_block(&mut block);
            a.copy_from_slice(&block[..8]);
            out[i * 8..i * 8 + 8].copy_from_slice(&block[8..]);
        }
    }
    // Integrity check: A must equal the default IV 0xA6A6A6A6A6A6A6A6.
    if a == [0xA6; 8] {
        Some(n * 8)
    } else {
        None
    }
}

/// NIST AES key wrap (RFC 3394), provided for completeness and tests.
pub fn key_wrap(kek: &[u8; 16], plain: &[u8], out: &mut [u8]) -> Option<usize> {
    if plain.len() < 16 || plain.len() % 8 != 0 || out.len() < plain.len() + 8 {
        return None;
    }
    let n = plain.len() / 8;
    let cipher = Aes128::new(kek);
    let mut a = [0xA6u8; 8];
    out[8..8 + plain.len()].copy_from_slice(plain);
    for j in 0..6 {
        for i in 0..n {
            let mut block = [0u8; 16];
            block[..8].copy_from_slice(&a);
            block[8..].copy_from_slice(&out[8 + i * 8..8 + i * 8 + 8]);
            cipher.encrypt_block(&mut block);
            let t = (n * j + i + 1) as u64;
            for k in 0..8 {
                a[k] = block[k] ^ ((t >> (8 * (7 - k))) & 0xff) as u8;
            }
            out[8 + i * 8..8 + i * 8 + 8].copy_from_slice(&block[8..]);
        }
    }
    out[..8].copy_from_slice(&a);
    Some(plain.len() + 8)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hex32(s: &str) -> [u8; 32] {
        let mut out = [0u8; 32];
        for (i, c) in s.as_bytes().chunks(2).enumerate() {
            out[i] = u8::from_str_radix(core::str::from_utf8(c).unwrap(), 16).unwrap();
        }
        out
    }

    #[test]
    fn fips197_vector() {
        let key = [
            0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d,
            0x0e, 0x0f,
        ];
        let mut block = [
            0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd,
            0xee, 0xff,
        ];
        aes128_encrypt_block(&key, &mut block);
        assert_eq!(
            block,
            [
                0x69, 0xc4, 0xe0, 0xd8, 0x6a, 0x7b, 0x04, 0x30, 0xd8, 0xcd, 0xb7, 0x80, 0x70,
                0xb4, 0xc5, 0x5a
            ]
        );
        aes128_decrypt_block(&key, &mut block);
        assert_eq!(block[0], 0x00);
        assert_eq!(block[15], 0xff);
    }

    #[test]
    fn rfc3394_vector() {
        // 128-bit KEK and 128-bit key data.
        let kek = hex32("000102030405060708090A0B0C0D0E0F")[..16].try_into().unwrap();
        let key = [
            0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd,
            0xee, 0xff,
        ];
        let mut wrapped = [0u8; 32];
        let n = key_wrap(&kek, &key, &mut wrapped).unwrap();
        assert_eq!(n, 24);
        assert_eq!(
            wrapped[..24],
            [
                0x1f, 0xa6, 0x8b, 0x0a, 0x81, 0x12, 0xb4, 0x47, 0xae, 0xf3, 0x4b, 0xd8, 0xfb,
                0x5a, 0x7b, 0x82, 0x9d, 0x3e, 0x86, 0x23, 0x71, 0xd2, 0xcf, 0xe5
            ]
        );
        let mut out = [0u8; 16];
        let m = key_unwrap(&kek, &wrapped[..24], &mut out).unwrap();
        assert_eq!(m, 16);
        assert_eq!(out, key);
    }
}
